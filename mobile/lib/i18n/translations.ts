/**
 * Translation dictionaries for the app-wide language setting (see
 * ../language-context.tsx). Hand-rolled rather than pulling in i18next —
 * this mirrors how the rest of the app avoids third-party state libraries
 * (theme-context.tsx does the same for light/dark) and three languages with
 * a few dozen keys doesn't need a library's overhead.
 *
 * Keys are dot-paths (e.g. "settings.darkMode") resolved by t() in
 * language-context.tsx. Pluralized keys have `.one` / `.other` children
 * resolved by tn() — this is a simplification (real Arabic plural rules
 * have more than two forms: zero/one/two/few/many/other) but matches the
 * two-way en/fr pluralization the app already had before translation
 * existed, applied consistently across all three languages.
 */
